    private void btnDepositarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositarActionPerformed
        if (contaSelecionada == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma conta primeiro."
            );
            return;
        }

        String valorTexto = JOptionPane.showInputDialog(
                this,
                "Digite o valor do depósito:"
        );

        double valor = Double.parseDouble(valorTexto);

        try {
            contasService.depositar(
                    contaSelecionada.getNumero(),
                    valor
            );

            carregarContasNaTabela();

            JOptionPane.showMessageDialog(
                    this,
                    "Depósito realizado com sucesso!"
            );
        } catch (ValorNegativoException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        } catch (SQLException ex) {
            System.getLogger(TabelaContas.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnDepositarActionPerformed

    private void tabelaContasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaContasMouseClicked
        int linhaSelecionada = tabelaContas.getSelectedRow();

        if (linhaSelecionada != -1) {
            contaSelecionada = contasService.getContas().get(linhaSelecionada);
        }
    }//GEN-LAST:event_tabelaContasMouseClicked

    private void btnSacarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacarActionPerformed
        if (contaSelecionada == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma conta primeiro."
            );
            return;
        }

        String valorTexto = JOptionPane.showInputDialog(
                this,
                "Digite o valor do saque:"
        );

        double valor = Double.parseDouble(valorTexto);

        if (valor <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Digite um valor maior que 0 para sacar.",
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try {
            contasService.sacar(
                    contaSelecionada.getNumero(),
                    valor
            );

            carregarContasNaTabela();

            JOptionPane.showMessageDialog(
                    this,
                    "Saque realizado com sucesso!"
            );
        } catch (SaldoInsuficienteException | ValorNegativoException e) {
            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Erro",
                    JOptionPane.ERROR_MESSAGE
            );
        } catch (SQLException ex) {
            System.getLogger(TabelaContas.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnSacarActionPerformed

    private void btnDeletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarActionPerformed
        if (contaSelecionada == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma conta primeiro.",
                    "Atenção",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir a conta "
                + contaSelecionada.getNumero() + "?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {
            try {
                boolean removida;
                removida = contasService.removerConta(
                        contaSelecionada.getNumero()
                );

                if (removida) {
                    contaSelecionada = null;

                    carregarContasNaTabela();

                    JOptionPane.showMessageDialog(
                            this,
                            "Conta removida com sucesso!"
                    );
                }
            } catch (SQLException ex) {
                System.getLogger(TabelaContas.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }
    }//GEN-LAST:event_btnDeletarActionPerformed


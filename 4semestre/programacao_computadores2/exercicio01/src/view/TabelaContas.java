    protected void carregarContasNaTabela() {

        DefaultTableModel modelo = new DefaultTableModel();

        modelo.addColumn("Número");
        modelo.addColumn("Titular");
        modelo.addColumn("Saldo");

        for (ContaCorrente conta : contasService.getContas()) {
            modelo.addRow(new Object[]{
                conta.getNumero(),
                conta.getTitular(),
                conta.getSaldo()
            });
        }

        tabelaContas.setModel(modelo);
    }
